-- ULVA · Sugestão de pedido do FLV
-- Venda do mesmo dia na mesma semana do mês anterior + margem de quebra,
-- menos o estoque contado na câmara (em caixas), convertido pela tabela
-- de conversão (kg ou unidades por embalagem).
--
-- Como rodar: SQL Editor do Supabase → New query → cola tudo → Run.
-- Pode rodar de novo sem duplicar (atualiza os fatores de conversão).

create table if not exists flv_conversao (
  codigo text primary key,
  produto text not null,
  controla text not null check (controla in ('KG','UN')),
  embalagem text,
  kg_por_emb numeric,
  un_por_emb numeric,
  atualizado_em timestamptz not null default now()
);

create table if not exists flv_contagem_camara (
  data_pedido date not null,
  codigo text not null,
  caixas numeric not null default 0,
  contado_por text,
  atualizado_em timestamptz not null default now(),
  primary key (data_pedido, codigo)
);

alter table flv_conversao enable row level security;
alter table flv_contagem_camara enable row level security;
drop policy if exists "Permitir tudo" on flv_conversao;
create policy "Permitir tudo" on flv_conversao for all using (true) with check (true);
drop policy if exists "Permitir tudo" on flv_contagem_camara;
create policy "Permitir tudo" on flv_contagem_camara for all using (true) with check (true);

